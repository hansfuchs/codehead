"""Ink layout of every printable ASCII glyph in JetBrains Mono → examples/lab/glyphs.rs.

Each glyph is drawn into 1 terminal cell (advance width x 2 widths high, baseline as in a
terminal), then split into 3 x 5 regions; a region's value = the share of its pixels inked.
Run: python3 examples/lab/tools/glyphs.py <JetBrainsMono-Regular.ttf>
"""
import sys, os
from PIL import Image, ImageDraw, ImageFont

font_path = sys.argv[1]
W = 60
H = 2 * W
COLS, ROWS = 3, 5
font = ImageFont.truetype(font_path, 100)
adv = font.getlength("M")
size = 100 * W / adv
font = ImageFont.truetype(font_path, round(size))
asc, desc = font.getmetrics()
# center the font's line box in the cell, like a terminal with line height ~2x the width
top = (H - (asc + desc)) / 2

rows = []
for code in range(32, 127):
    ch = chr(code)
    img = Image.new("L", (W, H), 0)
    ImageDraw.Draw(img).text((0, top), ch, fill=255, font=font)
    px = img.load()
    v = []
    for ry in range(ROWS):
        for rx in range(COLS):
            x0, x1 = rx * W // COLS, (rx + 1) * W // COLS
            y0, y1 = ry * H // ROWS, (ry + 1) * H // ROWS
            s = sum(px[x, y] for x in range(x0, x1) for y in range(y0, y1))
            v.append(s / (255 * (x1 - x0) * (y1 - y0)))
    rows.append((ch, v))

out = os.path.join(os.path.dirname(__file__), "..", "glyphs.rs")
with open(out, "w") as f:
    f.write("//! Generated by tools/glyphs.py from JetBrains Mono: per printable ASCII glyph, the share of\n")
    f.write("//! inked pixels in 3x5 regions of its cell (row-major, top left first).\n\n")
    f.write(f"pub const COLS: usize = {COLS};\npub const ROWS: usize = {ROWS};\n\n")
    f.write(f"pub const GLYPHS: [(char, [f32; {COLS * ROWS}]); {len(rows)}] = [\n")
    for ch, v in rows:
        lit = {"'": "'\\''", "\\": "'\\\\'"}.get(ch, f"'{ch}'")
        f.write(f"    ({lit}, [{', '.join(f'{x:.3f}' for x in v)}]),\n")
    f.write("];\n")
print("wrote", out, len(rows), "glyphs; max", max(max(v) for _, v in rows))
